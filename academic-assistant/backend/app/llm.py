"""LLM provider wrapper using the official Groq API."""
import os
import re
import time
import json
import contextvars
from typing import Optional, Any, Type
from groq import Groq, RateLimitError, APIStatusError
from pydantic import BaseModel, ValidationError
from app.config import GROQ_API_KEY, GROQ_MODEL_MAIN, GROQ_MODEL_FAST

# Singleton client reference
_client: Optional[Groq] = None

# Thread-local storage for request/thread level call stats
import threading

class CallStatsLocal:
    def __init__(self):
        self.call_count = 0
        self.rate_limit_retries = 0
        self.records = []

_thread_local = threading.local()


def _get_stats_tracker() -> CallStatsLocal:
    if not hasattr(_thread_local, "stats"):
        _thread_local.stats = CallStatsLocal()
    return _thread_local.stats


def get_call_count() -> int:
    """Returns the total number of LLM completion calls made in the current thread/request."""
    return _get_stats_tracker().call_count


def reset_call_count() -> None:
    """Resets the LLM call counter to zero in the current thread/request."""
    _get_stats_tracker().call_count = 0


def get_call_stats() -> dict:
    """Returns aggregated call stats: total calls, 429 retries, slowest call info, call records."""
    tracker = _get_stats_tracker()
    slowest_seconds = 0.0
    slowest_model = "none"
    for r in tracker.records:
        if r.get("seconds", 0.0) > slowest_seconds:
            slowest_seconds = r["seconds"]
            slowest_model = r.get("model", "unknown")
    return {
        "call_count": tracker.call_count,
        "rate_limit_retries": tracker.rate_limit_retries,
        "slowest_seconds": slowest_seconds,
        "slowest_model": slowest_model,
        "records": list(tracker.records),
    }


def reset_call_stats() -> None:
    """Resets call counter, 429 retries, and call records in current thread/request."""
    tracker = _get_stats_tracker()
    tracker.call_count = 0
    tracker.rate_limit_retries = 0
    tracker.records = []




def estimate_tokens(text: str) -> int:
    """Estimates the token count of a given string (len(text) // 4)."""
    return len(text) // 4


def strip_reasoning_content(text: str) -> str:
    """Strips chain-of-thought/reasoning content if embedded in model responses.

    Handles <think>...</think>, <thought>...</thought>, [Thinking]...[/Thinking],
    and similar reasoning blocks generated by reasoning LLMs.
    """
    if not text:
        return ""

    # Remove xml-style reasoning tags (e.g. <think>...</think>)
    cleaned = re.sub(r"<(?:think|thought)>.*?</(?:think|thought)>", "", text, flags=re.DOTALL | re.IGNORECASE)
    # Remove bracket-style reasoning tags (e.g. [Thinking]...[/Thinking])
    cleaned = re.sub(r"\[(?:thinking|reasoning)\].*?\[/(?:thinking|reasoning)\]", "", cleaned, flags=re.DOTALL | re.IGNORECASE)

    return cleaned.strip()


def get_groq_client(api_key: Optional[str] = None) -> Groq:
    """Returns a cached or new Groq client instance.

    Args:
        api_key: Optional override for the Groq API key.

    Returns:
        Groq client instance.

    Raises:
        ValueError: If no GROQ_API_KEY is found in the environment or parameters.
    """
    global _client
    key = api_key if api_key is not None else (os.getenv("GROQ_API_KEY") or GROQ_API_KEY)
    if not key:
        raise ValueError(
            "GROQ_API_KEY not set. Please set GROQ_API_KEY in your .env file or environment."
        )
    if _client is None or getattr(_client, "api_key", None) != key:
        _client = Groq(api_key=key)
    return _client


def generate(
    prompt: str,
    system: Optional[str] = None,
    model: Optional[str] = None,
    temperature: float = 0.2,
    max_retries: int = 10,
    initial_backoff: float = 1.0,
    backoff_factor: float = 2.0,
) -> str:
    """Generates a text completion using the Groq API with rate-limit retries.

    Provider-agnostic interface signature: generate(prompt, system=None, model=None) -> str.

    Args:
        prompt: User prompt content.
        system: Optional system instructions.
        model: Optional model name. Defaults to GROQ_MODEL_MAIN from config.py.
        temperature: Sampling temperature for generation.
        max_retries: Maximum number of retries upon encountering rate-limit errors.
        initial_backoff: Starting delay in seconds for backoff.
        backoff_factor: Multiplier applied to backoff after each rate limit hit.

    Returns:
        Generated assistant text string.

    Raises:
        RateLimitError: If rate limit retries are exhausted.
        APIStatusError: For non-rate-limit API failure codes.
    """
    client = get_groq_client()
    selected_model = model or GROQ_MODEL_MAIN

    messages = []
    if system:
        messages.append({"role": "system", "content": system})
    messages.append({"role": "user", "content": prompt})

    delay = initial_backoff
    attempt_retries_429 = 0
    t_start = time.time()
    for attempt in range(max_retries + 1):
        try:
            global _call_count, _rate_limit_retries, _call_records
            response = client.chat.completions.create(
                messages=messages,
                model=selected_model,
                temperature=temperature,
            )
            elapsed = time.time() - t_start
            # Success
            tracker = _get_stats_tracker()
            tracker.call_count += 1
            tracker.rate_limit_retries += attempt_retries_429
            tracker.records.append({
                "model": selected_model,
                "seconds": elapsed,
                "retries_429": attempt_retries_429,
            })
            # Extract message content, ignoring separate reasoning attributes if present
            message = response.choices[0].message
            content = getattr(message, "content", "") or ""
            # Strip reasoning blocks if embedded
            clean_content = strip_reasoning_content(content)
            return clean_content
        except RateLimitError as e:
            attempt_retries_429 += 1
            # Check if groq provided a retry-after message like 'Please try again in X.Xs'
            retry_match = re.search(r"try again in ([\d\.]+)s", str(e))
            sleep_time = float(retry_match.group(1)) + 1.0 if retry_match else delay
            if attempt == max_retries:
                _get_stats_tracker().rate_limit_retries += attempt_retries_429
                raise e
            time.sleep(sleep_time)
            delay = min(delay * backoff_factor, 15.0)
        except APIStatusError as e:
            # Handle HTTP 429 status if delivered as general APIStatusError
            if getattr(e, "status_code", None) == 429 and attempt < max_retries:
                attempt_retries_429 += 1
                retry_match = re.search(r"try again in ([\d\.]+)s", str(e))
                sleep_time = float(retry_match.group(1)) + 1.0 if retry_match else delay
                time.sleep(sleep_time)
                delay *= backoff_factor
                continue
            if getattr(e, "status_code", None) == 429:
                _get_stats_tracker().rate_limit_retries += attempt_retries_429
            raise e


def extract_json_object(text: str) -> str:
    """Extracts JSON object string from text, stripping markdown code fences."""
    if not text:
        return ""
    # Strip markdown code fences if present: ```json ... ``` or ``` ... ```
    fenced_match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", text, re.IGNORECASE)
    if fenced_match:
        text = fenced_match.group(1).strip()
    else:
        text = text.strip()

    # If text is still wrapped in surrounding non-JSON commentary, isolate outermost { ... } or [ ... ]
    brace_start = text.find("{")
    bracket_start = text.find("[")

    if brace_start != -1 and (bracket_start == -1 or brace_start < bracket_start):
        brace_end = text.rfind("}")
        if brace_end != -1 and brace_end > brace_start:
            return text[brace_start : brace_end + 1].strip()
    elif bracket_start != -1:
        bracket_end = text.rfind("]")
        if bracket_end != -1 and bracket_end > bracket_start:
            return text[bracket_start : bracket_end + 1].strip()

    return text


def generate_json(
    prompt: str,
    system: Optional[str] = None,
    model: Optional[str] = None,
    schema: Optional[Type[BaseModel]] = None,
    temperature: float = 0.2,
) -> dict:
    """Generates JSON output with markdown stripping, Pydantic validation, and single retry on error.

    Args:
        prompt: User prompt content.
        system: Optional system instructions.
        model: Optional model name.
        schema: Optional Pydantic BaseModel class for validation.
        temperature: Sampling temperature.

    Returns:
        Validated dict (or schema model dump).

    Raises:
        ValueError: If JSON is invalid or fails schema validation even after retry.
    """
    current_prompt = prompt
    last_error: Optional[Exception] = None

    for attempt in range(2):
        raw_text = generate(prompt=current_prompt, system=system, model=model, temperature=temperature)
        json_str = extract_json_object(raw_text)

        try:
            parsed = json.loads(json_str, strict=False)
            if schema:
                validated = schema.model_validate(parsed)
                return validated.model_dump()
            if isinstance(parsed, dict):
                return parsed
            if isinstance(parsed, list):
                return {"items": parsed}
            raise ValueError(f"Expected JSON object or list, got {type(parsed).__name__}")
        except (json.JSONDecodeError, ValidationError, ValueError) as e:
            # If standard json.loads failed on invalid escapes (common with LaTeX formulas like \frac or \alpha),
            # sanitize unescaped backslashes and retry parsing before calling LLM again
            if isinstance(e, json.JSONDecodeError) and "Invalid \\escape" in str(e):
                try:
                    sanitized_json = re.sub(r'\\(?![/"\\bfnrtu])', r'\\\\', json_str)
                    parsed = json.loads(sanitized_json, strict=False)
                    if schema:
                        validated = schema.model_validate(parsed)
                        return validated.model_dump()
                    if isinstance(parsed, dict):
                        return parsed
                    if isinstance(parsed, list):
                        return {"items": parsed}
                except Exception:
                    pass
            last_error = e
            if attempt == 0:
                current_prompt = (
                    f"{prompt}\n\nIMPORTANT: Your previous output was not valid JSON or did not match "
                    f"the required schema ({str(e)}). Return valid JSON only with no conversational text."
                )

    raise ValueError(f"Failed to generate valid JSON matching schema after retry: {last_error}")

